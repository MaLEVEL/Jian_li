def _material(material_id: str, title: str, content: str, tags: list[str]) -> dict:
    return {
        "id": material_id,
        "title": title,
        "content": content,
        "tags": tags,
        "created_at": "2026-11-18T00:00:00Z",
    }


def _retrieval_case(
    case_id: str,
    query: str,
    materials: list[dict],
    relevant_ids: list[str],
) -> dict:
    return {
        "id": case_id,
        "synthetic": True,
        "query": query,
        "materials": materials,
        "relevant_ids": relevant_ids,
        "top_k": 3,
    }


